"""
situation_room — daily intelligence digest.

Pulls articles from three world-news RSS feeds, classifies severity,
identifies the geographic location, writes a short briefing for each,
displays critical ones in the terminal, and saves all briefings to a
JSONL file.

Generated by Claude (sonnet-4-6) for Mani's situation_room spec, with
no prompting constraints — this is Claude's natural asyncio idiom.
"""

from __future__ import annotations

import asyncio
import json
from pathlib import Path

import feedparser
from anthropic import AsyncAnthropic


MODEL = "claude-sonnet-4-6"
OUTPUT_PATH = Path("briefings.jsonl")

FEEDS = {
    "bbc":        "http://feeds.bbci.co.uk/news/world/rss.xml",
    "npr":        "https://feeds.npr.org/1004/rss.xml",
    "al_jazeera": "https://www.aljazeera.com/xml/rss/all.xml",
}


# --------------------------------------------------------------------------- #
# Article fetching                                                            #
# --------------------------------------------------------------------------- #


async def fetch_articles(name: str, url: str, max_articles: int = 3) -> list[dict]:
    """Fetch up to `max_articles` from one RSS feed, in a thread."""
    loop = asyncio.get_event_loop()
    parsed = await loop.run_in_executor(None, feedparser.parse, url)
    return [
        {
            "source": name,
            "title": entry.title,
            "body": getattr(entry, "summary", entry.title),
            "url": entry.link,
        }
        for entry in parsed.entries[:max_articles]
    ]


# --------------------------------------------------------------------------- #
# LLM-driven enrichments                                                      #
# --------------------------------------------------------------------------- #


async def classify_severity(client: AsyncAnthropic, article: dict) -> str:
    """Classify the article's severity as LOW, MEDIUM, HIGH, or CRITICAL."""
    response = await client.messages.create(
        model=MODEL,
        max_tokens=20,
        system=(
            "You classify news article severity. "
            "Respond with exactly one of: LOW, MEDIUM, HIGH, CRITICAL. "
            "Nothing else."
        ),
        messages=[{"role": "user", "content": f"{article['title']}\n\n{article['body']}"}],
    )
    return response.content[0].text.strip().upper()


async def identify_location(client: AsyncAnthropic, article: dict) -> str:
    """Identify the article's primary geographic location."""
    response = await client.messages.create(
        model=MODEL,
        max_tokens=60,
        system=(
            "You identify the primary geographic location of a news article. "
            "Respond with 'Country, City' if both are clear, just 'Country' if "
            "only that is clear, or 'Global' if no specific location applies."
        ),
        messages=[{"role": "user", "content": f"{article['title']}\n\n{article['body']}"}],
    )
    return response.content[0].text.strip()


async def write_briefing(client: AsyncAnthropic, article: dict) -> str:
    """Write a short briefing using the article body, severity, and location."""
    response = await client.messages.create(
        model=MODEL,
        max_tokens=300,
        system=(
            "You write short, factual news briefings. "
            "Write 2-3 sentences summarising the situation. "
            "Mention the location and reflect the assigned severity."
        ),
        messages=[{"role": "user", "content": (
            f"Title: {article['title']}\n"
            f"Body: {article['body']}\n"
            f"Severity: {article['severity']}\n"
            f"Location: {article['location']}\n"
        )}],
    )
    return response.content[0].text.strip()


# --------------------------------------------------------------------------- #
# Per-article pipeline                                                        #
# --------------------------------------------------------------------------- #


async def enrich_article(client: AsyncAnthropic, article: dict) -> dict:
    """Run a single article through the enrichment pipeline."""
    # Severity and location are independent — run them in parallel.
    severity, location = await asyncio.gather(
        classify_severity(client, article),
        identify_location(client, article),
    )
    article["severity"] = severity
    article["location"] = location
    # Briefing depends on the two prior fields.
    article["briefing"] = await write_briefing(client, article)
    return article


# --------------------------------------------------------------------------- #
# Output                                                                      #
# --------------------------------------------------------------------------- #


def emit_outputs(articles: list[dict]) -> None:
    """Display critical briefings; save all to JSONL."""
    with OUTPUT_PATH.open("w") as f:
        for article in articles:
            if article["severity"] == "CRITICAL":
                print("=" * 60)
                print(f"[CRITICAL] {article['location']}")
                print(article["briefing"])
                print(f"  source: {article['source']}  url: {article['url']}")
                print("=" * 60)
            f.write(json.dumps(article) + "\n")
    print(f"\nWrote {len(articles)} briefings to {OUTPUT_PATH}")


# --------------------------------------------------------------------------- #
# Main                                                                        #
# --------------------------------------------------------------------------- #


async def main() -> None:
    client = AsyncAnthropic()

    # Fetch from all feeds concurrently.
    article_lists = await asyncio.gather(
        *(fetch_articles(name, url) for name, url in FEEDS.items())
    )
    articles = [a for lst in article_lists for a in lst]
    print(f"Fetched {len(articles)} articles total.")

    # Enrich every article concurrently.
    enriched = await asyncio.gather(*(enrich_article(client, a) for a in articles))

    emit_outputs(enriched)


if __name__ == "__main__":
    asyncio.run(main())
