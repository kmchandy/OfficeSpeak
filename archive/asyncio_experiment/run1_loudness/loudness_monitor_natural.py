"""
loudness_monitor — RMS-based loud-sound detector.

Pat's spec: watch a microphone, compute loudness (RMS) over short
windows, alert when loudness exceeds a threshold, save all measurements
to JSONL.

Generated by Claude with no prompting constraints — natural asyncio
idiom for a stateful, Python-not-LLM pipeline.

This sandbox version uses a synthetic audio source (no microphone).
The structure is identical to what a microphone-based version would
look like; only `audio_source` would change.
"""

from __future__ import annotations

import asyncio
import json
import math
import time
from collections import deque
from pathlib import Path


OUTPUT_PATH = Path(__file__).parent / "loudness_log.jsonl"


# --------------------------------------------------------------------------- #
# Audio source (synthetic — replace with mic / file in production)            #
# --------------------------------------------------------------------------- #


async def audio_source(num_samples: int = 2000, sample_rate_hz: float = 1000):
    """Async generator yielding synthetic audio samples.

    Produces three loud bursts amid mostly quiet background — so the
    detector should fire a small number of times.
    """
    period = 1.0 / sample_rate_hz
    for i in range(num_samples):
        if 300 <= i < 360:           # quick burst
            sample = 0.6 * math.sin(i * 0.4)
        elif 1000 <= i < 1100:       # sustained loud passage
            sample = 0.75 * math.sin(i * 0.25)
        elif 1700 <= i < 1750:       # short loud event
            sample = 0.5 * math.sin(i * 0.3)
        else:
            sample = 0.03 * math.sin(i * 0.05)
        yield sample
        await asyncio.sleep(period)


# --------------------------------------------------------------------------- #
# RMS meter — stateful, maintains a rolling window                            #
# --------------------------------------------------------------------------- #


class RMSMeter:
    """Compute root-mean-square loudness over a rolling window of samples."""

    def __init__(self, window_size: int = 50):
        self.window: deque[float] = deque(maxlen=window_size)

    def update(self, sample: float) -> float:
        self.window.append(sample)
        if not self.window:
            return 0.0
        return math.sqrt(sum(s * s for s in self.window) / len(self.window))


# --------------------------------------------------------------------------- #
# Threshold detector — stateful, edge-triggered                               #
# --------------------------------------------------------------------------- #


class ThresholdDetector:
    """Flag the rising edge when RMS crosses above a threshold."""

    def __init__(self, threshold: float = 0.3):
        self.threshold = threshold
        self.was_loud = False

    def check(self, rms: float) -> tuple[bool, bool]:
        """Return (is_loud, rising_edge)."""
        is_loud = rms > self.threshold
        rising = is_loud and not self.was_loud
        self.was_loud = is_loud
        return is_loud, rising


# --------------------------------------------------------------------------- #
# Main pipeline                                                               #
# --------------------------------------------------------------------------- #


async def main() -> None:
    meter = RMSMeter(window_size=50)
    detector = ThresholdDetector(threshold=0.3)

    alert_count = 0
    total = 0

    with OUTPUT_PATH.open("w") as f:
        async for sample in audio_source(num_samples=2000):
            rms = meter.update(sample)
            is_loud, rising = detector.check(rms)

            record = {
                "t": total,
                "sample": sample,
                "rms": rms,
                "is_loud": is_loud,
            }
            f.write(json.dumps(record) + "\n")

            if rising:
                alert_count += 1
                print(f"[ALERT #{alert_count}] t={total} rms={rms:.3f}")

            total += 1

    print(f"\nDone. {total} samples processed; {alert_count} loud-event alerts.")
    print(f"Wrote per-sample log to {OUTPUT_PATH}")


if __name__ == "__main__":
    asyncio.run(main())
