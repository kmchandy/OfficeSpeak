"""
Claudette smoke test 2: end-to-end through DSL.

Tests the claim:
    A role.md file produced by smoke test 1 (Claudette + wrapper)
    can be dropped into a DSL office, built via `dsl build`, and run
    via `dsl run`, producing sensible output on cached test articles.

Steps:
    1. Locate the credibility_scorer.md generated by smoke test 1.
       (If missing, instruct user to run smoke test 1 first.)
    2. Create a temp office directory:
         <tmp>/credibility_test/
           ├── office.md             (defines the test office)
           ├── articles.jsonl        (3 cached test articles)
           └── roles/
               └── credibility_scorer.md  (copied from smoke test 1)
    3. Run `dsl build <office_dir>`. Report success/failure.
    4. Run `dsl run <office_dir>`. Report success/failure.
    5. Read results.jsonl and verify:
       - one record per input article
       - each has `score` and `reasoning` fields
       - scores are valid floats in [0, 1]
       - reasonings are non-empty strings
    6. Report pass/fail with details.

Requires ANTHROPIC_API_KEY in the environment for the run step (the
agent calls Claude). Without the key, `dsl build` should still
succeed (validates the role file is well-formed); only `dsl run`
will fail. Both outcomes are useful information.
"""

from __future__ import annotations

